from typing import Any

from transformers import AutoModelForCausalLM, AutoTokenizer


class LLM:
    """Wrapper around a local causal language model used for answer generation.

    Attributes:
        model_name: Hugging Face model identifier used for initialization.
        tokenizer: Tokenizer coupled to the selected model.
        model: Loaded model instance.
    """

    def __init__(self, model_name: str = "Qwen/Qwen3-0.6B") -> None:
        """Initialize the model and tokenizer.

        Args:
            model_name: Name of the Hugging Face model to load.
        """
        self.model_name: str = model_name
        self.tokenizer: Any = AutoTokenizer.from_pretrained(model_name)
        self.model: Any = AutoModelForCausalLM.from_pretrained(
            model_name, torch_dtype="auto", device_map="auto"
        )

    def generate(self, prompt: str) -> Any:
        """Generate a response from the model for a given prompt.

        Args:
            prompt: The prompt text to send to the model.

        Returns:
            The decoded text generated by the model.
        """
        messages = [{"role": "user", "content": prompt}]
        text = self.tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True,
            enable_thinking=False,
        )
        model_inputs = self.tokenizer([text], return_tensors="pt").to(
            self.model.device
        )

        generated_ids = self.model.generate(
            **model_inputs, max_new_tokens=32768
        )

        output_ids = generated_ids[0][
            len(model_inputs.input_ids[0]) :
        ].tolist()

        content = self.tokenizer.decode(
            output_ids, skip_special_tokens=True
        ).strip("\n")
        return content


if __name__ == "__main__":
    llm = LLM()
    result = llm.generate("Hello, are you machine?")
    print(result)
